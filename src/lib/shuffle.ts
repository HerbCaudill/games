/** Return a shuffled copy of a list. */
export function shuffle<T>(
  /** Items to shuffle. */
  items: T[],
): T[] {
  const result = [...items]
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[result[i], result[j]] = [result[j], result[i]]
  }
  return result
}
